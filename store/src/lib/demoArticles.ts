let keySeq = 0;
const k = () => `k${keySeq++}`;

function para(text: string): PortableTextBlock {
  return {
    _type: "block",
    _key: k(),
    style: "normal",
    markDefs: [],
    children: [{ _type: "span", _key: k(), text, marks: [] }],
  } as unknown as PortableTextBlock;
}
function heading(text: string, style: "h2" | "h3" = "h2"): PortableTextBlock {
  return {
    _type: "block",
    _key: k(),
    style,
    markDefs: [],
    children: [{ _type: "span", _key: k(), text, marks: [] }],
  } as unknown as PortableTextBlock;
}
function bullet(text: string): PortableTextBlock {
  return {
    _type: "block",
    _key: k(),
    style: "normal",
    listItem: "bullet",
    level: 1,
    markDefs: [],
    children: [{ _type: "span", _key: k(), text, marks: [] }],
  } as unknown as PortableTextBlock;
}

