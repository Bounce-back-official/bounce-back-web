// ---- helper สร้างบล็อกเนื้อหา (Portable Text) ให้เขียนตัวอย่างง่าย ๆ ----
let keySeq = 0;
const k = () => `k${keySeq++}`;

function para(text: string): PortableTextBlock {
  return {
    _type: "block",
    _key: k(),
    style: "normal",
    markDefs: [],
    children: [{ _type: "span", _key: k(), text, marks: [] }],
  } as unknown as PortableTextBlock;
}
function heading(text: string): PortableTextBlock {
  return {
    _type: "block",
    _key: k(),
    style: "h2",
    markDefs: [],
    children: [{ _type: "span", _key: k(), text, marks: [] }],
  } as unknown as PortableTextBlock;
}
function bullet(text: string): PortableTextBlock {
  return {
    _type: "block",
    _key: k(),
    style: "normal",
    listItem: "bullet",
    level: 1,
    markDefs: [],
    children: [{ _type: "span", _key: k(), text, marks: [] }],
  } as unknown as PortableTextBlock;
}

